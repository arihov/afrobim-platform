//! The design catalogue of the MoWT Road Design Manual Volume 3, Part I (January 2010),
//! Appendix C: charts D1 to D5 (dry regions) and W1 to W5 (wet regions), pages C-2 to C-11.
//!
//! # How these numbers were obtained
//!
//! The charts are raster images in the published PDF (about 98 pixels per inch; W3 is a redrawn
//! image at 124). Every cell was read from the page rendered at 300 dpi and, where a label was
//! small or clipped, from the embedded image enlarged pixel for pixel. Two checks were then made:
//!
//! - The surfacing label of every cell ("SD" or a thickness) was read again from an enlargement
//!   of the top of each column, because "SD" and "50" look alike at this resolution.
//! - The columns of nine charts are drawn to scale (0.106 to 0.111 pixel per mm). The drawn
//!   height of each of the 324 columns on those charts was measured and compared with the sum of
//!   the thicknesses read. All agree within 2 pixels (under 20 mm, less than the 25 mm step of
//!   the catalogue) except chart D3, S2/T4, noted below. Chart W3 is not drawn to scale, so its
//!   labels (which are the sharpest in the appendix) have no such check. A height check confirms
//!   a column's total, not the split between its layers.
//!
//! Each cell is `[surfacing, base, upper subbase, subbase, selected layer]` in millimetres. A
//! surfacing of 0 is the chart's "SD" (surface dressing, no thickness given). A layer of 0 is
//! absent. `X` is a cell the chart leaves empty.
//!
//! # Printed inconsistency kept as printed
//!
//! Chart D3, S2/T4 is labelled 175 base / 200 subbase / 225 selected, but its column is drawn
//! about 25 mm shorter than those labels add up to (the same height as S2/T3: 175/175/225).
//! The labels are what is stored; [`cell_note`] reports the doubt with the structure.

pub(crate) type Cell = Option<[u16; 5]>;
/// Rows S1..S6, columns T1..T8.
pub(crate) type Chart = [[Cell; 8]; 6];

const X: Cell = None;

const fn c(surfacing: u16, base: u16, upper_subbase: u16, subbase: u16, selected: u16) -> Cell {
    Some([surfacing, base, upper_subbase, subbase, selected])
}

/// A doubt about one printed cell, by chart name, subgrade index (0 = S1) and traffic index
/// (0 = T1).
pub(crate) fn cell_note(chart: &str, subgrade: usize, traffic: usize) -> Option<&'static str> {
    match (chart, subgrade, traffic) {
        ("D3", 1, 3) => Some(
            "Chart D3, S2/T4: the labels read 175 / 200 / 225 mm but the column is drawn about 25 mm shorter than their sum. The labels are used; confirm against another copy of the chart.",
        ),
        _ => None,
    }
}

