//! A small single-stroke font used only to preview text where the draw crate has no text
//! primitive. It is this crate's own design (a 4 by 6 cell per glyph), not a standard font.
//!
//! The real lettering is carried by [`crate::geometry::Label`]s; the DXF writer and the sheets
//! use those. The stroke preview is scaled so each glyph sits inside the advance width of the
//! Helvetica metrics used for layout, so a preview occupies the same footprint as the real text.

type S = &'static [(f64, f64)];

const ZERO: &[S] = &[&[(1., 0.), (3., 0.), (4., 1.), (4., 5.), (3., 6.), (1., 6.), (0., 5.), (0., 1.), (1., 0.)]];
const P: &[S] = &[&[(0., 0.), (0., 6.), (3., 6.), (4., 5.), (4., 4.), (3., 3.), (0., 3.)]];
const C: &[S] = &[&[(4., 5.), (3., 6.), (1., 6.), (0., 5.), (0., 1.), (1., 0.), (3., 0.), (4., 1.)]];
const BOX: &[S] = &[&[(0.5, 0.), (3.5, 0.), (3.5, 6.), (0.5, 6.), (0.5, 0.)]];

/// The strokes of `c` in a cell 4 wide and 6 high (capital letters, digits and a few signs).
/// Lower case is drawn as upper case. An unknown character is an empty box.
pub fn glyph(c: char) -> Vec<S> {
    let c = c.to_ascii_uppercase();
    let one: &[S] = match c {
        ' ' => &[],
        '0' | 'O' => ZERO,
        '1' => &[&[(1., 5.), (2., 6.), (2., 0.)], &[(1., 0.), (3., 0.)]],
        '2' => &[&[(0., 5.), (1., 6.), (3., 6.), (4., 5.), (4., 4.), (0., 0.), (4., 0.)]],
        '3' => &[&[(0., 5.), (1., 6.), (3., 6.), (4., 5.), (4., 4.), (3., 3.), (1.5, 3.)], &[(3., 3.), (4., 2.), (4., 1.), (3., 0.), (1., 0.), (0., 1.)]],
        '4' => &[&[(3., 0.), (3., 6.), (0., 2.), (4., 2.)]],
        '5' => &[&[(4., 6.), (0., 6.), (0., 3.), (3., 3.), (4., 2.), (4., 1.), (3., 0.), (1., 0.), (0., 1.)]],
        '6' => &[&[(4., 5.), (3., 6.), (1., 6.), (0., 5.), (0., 1.), (1., 0.), (3., 0.), (4., 1.), (4., 2.), (3., 3.), (0., 3.)]],
        '7' => &[&[(0., 6.), (4., 6.), (1.5, 0.)]],
        '8' => &[&[(1., 3.), (0., 4.), (0., 5.), (1., 6.), (3., 6.), (4., 5.), (4., 4.), (3., 3.), (1., 3.), (0., 2.), (0., 1.), (1., 0.), (3., 0.), (4., 1.), (4., 2.), (3., 3.)]],
        '9' => &[&[(0., 1.), (1., 0.), (3., 0.), (4., 1.), (4., 5.), (3., 6.), (1., 6.), (0., 5.), (0., 4.), (1., 3.), (4., 3.)]],
        'A' => &[&[(0., 0.), (2., 6.), (4., 0.)], &[(0.8, 2.), (3.2, 2.)]],
        'B' => &[&[(0., 0.), (0., 6.), (3., 6.), (4., 5.), (4., 4.), (3., 3.), (0., 3.)], &[(3., 3.), (4., 2.), (4., 1.), (3., 0.), (0., 0.)]],
        'C' => C,
        'D' => &[&[(0., 0.), (0., 6.), (2., 6.), (4., 4.), (4., 2.), (2., 0.), (0., 0.)]],
        'E' => &[&[(4., 6.), (0., 6.), (0., 0.), (4., 0.)], &[(0., 3.), (3., 3.)]],
        'F' => &[&[(4., 6.), (0., 6.), (0., 0.)], &[(0., 3.), (3., 3.)]],
        'G' => &[&[(4., 5.), (3., 6.), (1., 6.), (0., 5.), (0., 1.), (1., 0.), (3., 0.), (4., 1.), (4., 3.), (2., 3.)]],
        'H' => &[&[(0., 0.), (0., 6.)], &[(4., 0.), (4., 6.)], &[(0., 3.), (4., 3.)]],
        'I' => &[&[(1., 6.), (3., 6.)], &[(2., 6.), (2., 0.)], &[(1., 0.), (3., 0.)]],
        'J' => &[&[(4., 6.), (4., 1.), (3., 0.), (1., 0.), (0., 1.)]],
        'K' => &[&[(0., 0.), (0., 6.)], &[(4., 6.), (0., 2.5)], &[(1.2, 3.5), (4., 0.)]],
        'L' => &[&[(0., 6.), (0., 0.), (4., 0.)]],
        'M' => &[&[(0., 0.), (0., 6.), (2., 3.), (4., 6.), (4., 0.)]],
        'N' => &[&[(0., 0.), (0., 6.), (4., 0.), (4., 6.)]],
        'P' => P,
        'Q' => &[&[(1., 0.), (3., 0.), (4., 1.), (4., 5.), (3., 6.), (1., 6.), (0., 5.), (0., 1.), (1., 0.)], &[(2.5, 1.5), (4., 0.)]],
        'R' => &[&[(0., 0.), (0., 6.), (3., 6.), (4., 5.), (4., 4.), (3., 3.), (0., 3.)], &[(2., 3.), (4., 0.)]],
        'S' => &[&[(4., 5.), (3., 6.), (1., 6.), (0., 5.), (0., 4.), (1., 3.), (3., 3.), (4., 2.), (4., 1.), (3., 0.), (1., 0.), (0., 1.)]],
        'T' => &[&[(0., 6.), (4., 6.)], &[(2., 6.), (2., 0.)]],
        'U' => &[&[(0., 6.), (0., 1.), (1., 0.), (3., 0.), (4., 1.), (4., 6.)]],
        'V' => &[&[(0., 6.), (2., 0.), (4., 6.)]],
        'W' => &[&[(0., 6.), (1., 0.), (2., 4.), (3., 0.), (4., 6.)]],
        'X' => &[&[(0., 0.), (4., 6.)], &[(0., 6.), (4., 0.)]],
        'Y' => &[&[(0., 6.), (2., 3.), (4., 6.)], &[(2., 3.), (2., 0.)]],
        'Z' => &[&[(0., 6.), (4., 6.), (0., 0.), (4., 0.)]],
        '-' => &[&[(0.5, 3.), (3.5, 3.)]],
        '+' => &[&[(0.5, 3.), (3.5, 3.)], &[(2., 1.5), (2., 4.5)]],
        '.' => &[&[(1.8, 0.), (2.2, 0.), (2.2, 0.4), (1.8, 0.4), (1.8, 0.)]],
        ',' => &[&[(2., 0.4), (1.6, -0.8)]],
        ':' => &[&[(1.8, 0.), (2.2, 0.), (2.2, 0.4), (1.8, 0.4), (1.8, 0.)], &[(1.8, 3.), (2.2, 3.), (2.2, 3.4), (1.8, 3.4), (1.8, 3.)]],
        '/' => &[&[(0., 0.), (4., 6.)]],
        '(' => &[&[(3., 6.), (1.5, 4.), (1.5, 2.), (3., 0.)]],
        ')' => &[&[(1., 6.), (2.5, 4.), (2.5, 2.), (1., 0.)]],
        '%' => &[&[(0., 0.), (4., 6.)], &[(0.2, 5.), (1.2, 5.), (1.2, 6.), (0.2, 6.), (0.2, 5.)], &[(2.8, 0.), (3.8, 0.), (3.8, 1.), (2.8, 1.), (2.8, 0.)]],
        '\u{b0}' => &[&[(1.2, 4.5), (2.8, 4.5), (2.8, 6.), (1.2, 6.), (1.2, 4.5)]],
        '=' => &[&[(0.5, 2.), (3.5, 2.)], &[(0.5, 4.), (3.5, 4.)]],
        '<' => &[&[(3.5, 5.), (0.5, 3.), (3.5, 1.)]],
        '>' => &[&[(0.5, 5.), (3.5, 3.), (0.5, 1.)]],
        '\'' => &[&[(2., 6.), (2., 4.5)]],
        '"' => &[&[(1.2, 6.), (1.2, 4.5)], &[(2.8, 6.), (2.8, 4.5)]],
        '_' => &[&[(0., -0.8), (4., -0.8)]],
        '\u{b1}' => &[&[(0.5, 3.5), (3.5, 3.5)], &[(2., 2.), (2., 5.)], &[(0.5, 0.5), (3.5, 0.5)]],
        '\u{d8}' => &[&[(1., 0.), (3., 0.), (4., 1.), (4., 5.), (3., 6.), (1., 6.), (0., 5.), (0., 1.), (1., 0.)], &[(0., 0.), (4., 6.)]],
        _ => BOX,
    };
    one.to_vec()
}

/// The strokes of one line of text as polylines, in the text's own frame: the baseline starts at
/// the origin and runs along +X; `height` is the capital height and `width_factor` stretches the
/// advance widths. `advance(c)` gives the advance width of a character in the same units.
pub fn stroke_line(text: &str, height: f64, mut advance: impl FnMut(char) -> f64) -> Vec<Vec<(f64, f64)>> {
    let mut out = Vec::new();
    let mut x = 0.0;
    let k = height / 6.0;
    for c in text.chars() {
        let adv = advance(c);
        let xs = adv * 0.8 / 4.0;
        for s in glyph(c) {
            out.push(s.iter().map(|&(gx, gy)| (x + adv * 0.1 + gx * xs, gy * k)).collect());
        }
        x += adv;
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_stay_inside_the_cell_and_every_character_of_a_dimension_text_has_strokes() {
        for c in "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ+-.,:/()%\u{b0}=<>'\"_\u{b1}\u{d8}".chars() {
            let g = glyph(c);
            assert!(!g.is_empty(), "{c}");
            for s in g {
                for &(x, y) in s {
                    assert!((0.0..=4.0).contains(&x) && (-1.0..=6.0).contains(&y), "{c} {x} {y}");
                }
            }
        }
        assert!(glyph(' ').is_empty());
        assert_eq!(glyph('a'), glyph('A'));
    }

    #[test]
    fn a_line_advances_by_the_given_widths() {
        let s = stroke_line("11", 6.0, |_| 5.0);
        // Two glyphs of two strokes each; the second glyph starts 5 units later.
        assert_eq!(s.len(), 4);
        assert!((s[2][0].0 - s[0][0].0 - 5.0).abs() < 1e-12);
    }
}
