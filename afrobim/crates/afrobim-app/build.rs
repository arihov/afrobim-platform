//! Windows only: embeds the application icon and the version information in `afrobim.exe`, so the
//! file shows the icon in Explorer and the taskbar and a Details tab in its Properties.
//!
//! The resource script is written to the build's output folder from the crate's version and
//! compiled by the `embed-resource` crate, which finds `rc.exe` in the Windows SDK (the Visual
//! Studio build tools bring it; it is on the GitHub `windows-latest` image). On Linux and macOS
//! this script does nothing and the crate is not built.

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=../../packaging/icons/afrobim.ico");
    #[cfg(windows)]
    windows::embed();
}

#[cfg(windows)]
mod windows {
    use std::path::PathBuf;

    /// The resource script for a version `major.minor.patch` and the icon at `icon` (forward slashes).
    pub fn rc_text(version: &str, icon: &str) -> String {
        let mut parts = version.split(|c: char| !c.is_ascii_digit()).filter(|p| !p.is_empty()).map(|p| p.parse::<u32>().unwrap_or(0));
        let (major, minor, patch) = (parts.next().unwrap_or(0), parts.next().unwrap_or(0), parts.next().unwrap_or(0));
        format!(
            r#"// Generated by build.rs.
1 ICON "{icon}"

1 VERSIONINFO
FILEVERSION {major},{minor},{patch},0
PRODUCTVERSION {major},{minor},{patch},0
FILEOS 0x00040004L
FILETYPE 0x00000001L
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904B0"
    BEGIN
      VALUE "CompanyName", "AfroBIM"
      VALUE "FileDescription", "AfroBIM desktop application"
      VALUE "FileVersion", "{version}"
      VALUE "InternalName", "afrobim"
      VALUE "OriginalFilename", "afrobim.exe"
      VALUE "ProductName", "AfroBIM"
      VALUE "ProductVersion", "{version}"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x0409, 1200
  END
END
"#
        )
    }

    pub fn embed() {
        // The build runs on Windows, but the target may be another system.
        if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
            return;
        }
        let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"));
        let icon = manifest.join("../../packaging/icons/afrobim.ico");
        let icon = icon.to_string_lossy().replace('\\', "/");
        let version = std::env::var("CARGO_PKG_VERSION").expect("cargo sets CARGO_PKG_VERSION");
        let out = PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("afrobim.rc");
        std::fs::write(&out, rc_text(&version, &icon)).expect("write the resource script");
        embed_resource::compile(&out, embed_resource::NONE).manifest_required().expect("compile the Windows resources");
    }
}
