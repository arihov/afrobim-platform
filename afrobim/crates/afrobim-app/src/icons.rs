type Poly = &'static [(f32, f32)];

fn circle(cx: f32, cy: f32, r: f32) -> Vec<(f32, f32)> {
    (0..=20).map(|i| {
        let a = i as f32 / 20.0 * std::f32::consts::TAU;
        (cx + r * a.cos(), cy + r * a.sin())
    }).collect()
}

