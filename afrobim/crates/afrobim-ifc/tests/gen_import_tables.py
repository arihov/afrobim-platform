#!/usr/bin/env python3
"""Generates src/import/tables.rs from the EXPRESS schemas compiled into IfcOpenShell.

Attribute positions and the list of IfcProduct subtypes (with the position of PredefinedType)
come from `ifcopenshell.ifcopenshell_wrapper.schema_by_name`, not from memory. Run:

    python3 -I gen_import_tables.py > ../src/import/tables.rs      (rustfmt not applied)
    python3 -I gen_import_tables.py --check ../src/import/tables.rs

`--check` exits non-zero when the file differs from what the installed IfcOpenShell says; the
Rust test `import_tables_match_ifcopenshell` runs it when Python and IfcOpenShell are present.
"""
import sys

import ifcopenshell
import ifcopenshell.ifcopenshell_wrapper as w

SCHEMAS = [("IFC2X3", "IFC2X3"), ("IFC4", "IFC4"), ("IFC4X3", "IFC4X3_ADD2")]

ENTITIES = """IfcLocalPlacement IfcLinearPlacement IfcGridPlacement IfcAxis2Placement3D IfcAxis2Placement2D IfcCartesianPoint IfcDirection
IfcProductDefinitionShape IfcShapeRepresentation IfcTriangulatedFaceSet IfcPolygonalFaceSet IfcIndexedPolygonalFace IfcIndexedPolygonalFaceWithVoids
IfcCartesianPointList3D IfcFacetedBrep IfcClosedShell IfcOpenShell IfcFace IfcFaceBound IfcFaceOuterBound IfcPolyLoop IfcExtrudedAreaSolid
IfcArbitraryClosedProfileDef IfcArbitraryProfileDefWithVoids IfcPolyline IfcRectangleProfileDef IfcCircleProfileDef IfcMappedItem IfcRepresentationMap
IfcCartesianTransformationOperator3D IfcCartesianTransformationOperator3DnonUniform IfcBoundingBox IfcRelAggregates IfcRelContainedInSpatialStructure
IfcRelDefinesByProperties IfcPropertySet IfcPropertySingleValue IfcPropertyEnumeratedValue IfcPropertyListValue IfcElementQuantity IfcQuantityLength
IfcQuantityArea IfcQuantityVolume IfcQuantityCount IfcQuantityWeight IfcQuantityTime IfcProject IfcUnitAssignment IfcSIUnit IfcConversionBasedUnit
IfcMeasureWithUnit IfcMapConversion IfcProjectedCRS IfcIndexedPolyCurve IfcCartesianPointList2D IfcShellBasedSurfaceModel IfcFaceBasedSurfaceModel IfcConnectedFaceSet IfcProduct
IfcAxis2PlacementLinear IfcPointByDistanceExpression IfcCurveSegment IfcCompositeCurve IfcGradientCurve IfcLine IfcVector IfcCircle IfcClothoid IfcPolynomialCurve""".split()


def is_a(decl, name):
    d = decl
    while d is not None:
        if d.name() == name:
            return True
        d = d.supertype()
    return False


def main():
    out = []
    out.append("//! Generated by tests/gen_import_tables.py from the EXPRESS schemas compiled into IfcOpenShell %s." % ifcopenshell.version)
    out.append("//! Do not edit by hand. Attribute names in schema order (inherited first); IfcProduct subtypes with")
    out.append("//! the position of `PredefinedType` (-1 when the entity has none).")
    out.append("")
    out.append("pub(crate) struct Product {")
    out.append("    pub name: &'static str,")
    out.append("    pub predefined: i8,")
    out.append("    pub spatial: bool,")
    out.append("    pub opening: bool,")
    out.append("}")
    out.append("")
    out.append("#[allow(dead_code)]")
    out.append("pub(crate) struct SchemaTable {")
    out.append("    pub family: &'static str,")
    out.append("    pub express: &'static str,")
    out.append("    pub attrs: &'static [(&'static str, &'static [&'static str])],")
    out.append("    pub products: &'static [Product],")
    out.append("}")
    out.append("")
    names = []
    for fam, sch in SCHEMAS:
        s = w.schema_by_name(sch)
        var = "T_" + fam
        names.append(var)
        out.append("pub(crate) static %s: SchemaTable = SchemaTable {" % var)
        out.append('    family: "%s",' % fam)
        out.append('    express: "%s",' % sch)
        out.append("    attrs: &[")
        for e in sorted(ENTITIES, key=str.upper):
            try:
                d = s.declaration_by_name(e)
            except Exception:
                continue
            attrs = ", ".join('"%s"' % a.name() for a in d.all_attributes())
            out.append('        ("%s", &[%s]),' % (e.upper(), attrs))
        out.append("    ],")
        out.append("    products: &[")
        spatial_root = "IfcSpatialStructureElement" if fam != "IFC4X3" else "IfcSpatialElement"
        rows = []
        for d in s.entities():
            if not is_a(d, "IfcProduct"):
                continue
            attrs = [a.name() for a in d.all_attributes()]
            pre = attrs.index("PredefinedType") if "PredefinedType" in attrs else -1
            rows.append((d.name().upper(), pre, is_a(d, spatial_root), d.name() == "IfcOpeningElement" or is_a(d, "IfcOpeningElement")))
        for n, pre, sp, op in sorted(rows):
            out.append('        Product { name: "%s", predefined: %d, spatial: %s, opening: %s },' % (n, pre, str(sp).lower(), str(op).lower()))
        out.append("    ],")
        out.append("};")
        out.append("")
    out.append("pub(crate) static TABLES: [&SchemaTable; 3] = [%s];" % ", ".join("&" + n for n in names))
    text = "\n".join(out) + "\n"
    if len(sys.argv) > 2 and sys.argv[1] == "--check":
        cur = open(sys.argv[2]).read()
        if cur.split("\n", 1)[1] != text.split("\n", 1)[1]:  # the first line names the IfcOpenShell version
            sys.stderr.write("tables.rs differs from the installed IfcOpenShell schemas\n")
            sys.exit(1)
        return
    sys.stdout.write(text)


main()
