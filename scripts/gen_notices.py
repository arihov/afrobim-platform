"""Writes THIRD-PARTY-NOTICES.md from `cargo metadata`: every third-party Rust crate in the
locked dependency tree, with version, SPDX licence expression and licence text, grouped by
licence. Used by scripts/gen-notices.sh when `cargo about` is not installed.

Usage: gen_notices.py MANIFEST OUT [--check]
  --check  exit 1 if OUT differs from what would be written (for CI)
"""
import collections
import hashlib
import json
import os
import subprocess
import sys

manifest, out = sys.argv[1], sys.argv[2]
check = "--check" in sys.argv

meta = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--locked", "--manifest-path", manifest], text=True))
pkgs = [p for p in meta["packages"] if p.get("source")]  # path crates (AfroBIM's own) have no source
pkgs.sort(key=lambda p: (p["name"], p["version"]))

LICENSE_NAMES = ("licen", "copying", "copyright", "unlicense", "notice")


def texts(pkg):
    d = os.path.dirname(pkg["manifest_path"])
    found = []
    if not os.path.isdir(d):
        return found
    for root, dirs, files in os.walk(d):
        dirs[:] = [x for x in dirs if x not in ("target", "tests", "src", "benches", "examples", ".git")]
        if root != d and os.path.relpath(root, d).count(os.sep) > 1:
            continue
        for f in sorted(files):
            if f.lower().startswith(LICENSE_NAMES) and not f.lower().endswith((".rs", ".toml", ".json")):
                try:
                    t = open(os.path.join(root, f), encoding="utf-8", errors="replace").read().strip()
                except OSError:
                    continue
                if t:
                    found.append((os.path.relpath(os.path.join(root, f), d), t))
    return found


groups = collections.defaultdict(list)
missing = []
for p in pkgs:
    lic = (p.get("license") or "").strip()
    if not lic and p.get("license_file"):
        lic = "SEE LICENCE FILE (%s)" % p["license_file"]
    lic = lic or "UNKNOWN"
    groups[lic].append(p)
    if not texts(p):
        missing.append("%s %s" % (p["name"], p["version"]))

L = []
L.append("# Third-party notices (Rust dependencies)\n")
L.append("This file lists every third-party Rust crate compiled into AfroBIM, with its version, its SPDX licence expression and the licence text supplied by its authors. It is generated by `scripts/gen-notices.sh` from `afrobim/Cargo.lock`; do not edit it by hand.\n")
L.append("Where a crate offers a choice (for example `MIT OR Apache-2.0`), AfroBIM may use it under any of the options offered. Other notices (acadrust, ACadSharp, BIMCraft, fonts, icons, map tile providers) are in `NOTICE`. AfroBIM's own code is proprietary (`LICENSE`).\n")
L.append("Total: %d third-party crates in %d licence groups.\n" % (len(pkgs), len(groups)))
L.append("## Contents\n")
for lic in sorted(groups):
    L.append("* [%s](#%s) (%d)" % (lic, "g-" + "".join(c.lower() if c.isalnum() else "-" for c in lic).strip("-"), len(groups[lic])))
L.append("")
for lic in sorted(groups):
    anchor = "g-" + "".join(c.lower() if c.isalnum() else "-" for c in lic).strip("-")
    L.append('<a id="%s"></a>\n## %s\n' % (anchor, lic))
    L.append("Crates:\n")
    for p in groups[lic]:
        extra = ""
        if p.get("repository"):
            extra = " (%s)" % p["repository"]
        L.append("* %s %s%s" % (p["name"], p["version"], extra))
    L.append("")
    byhash = collections.OrderedDict()
    for p in groups[lic]:
        for fname, t in texts(p):
            h = hashlib.sha256(" ".join(t.split()).encode()).hexdigest()
            byhash.setdefault(h, [t, []])[1].append("%s %s" % (p["name"], p["version"]))
    for h, (t, who) in byhash.items():
        L.append("### Licence text used by: %s\n" % ", ".join(who))
        L.append("```text\n%s\n```\n" % t.replace("```", "'''"))
MIT = """MIT License

Copyright (c) {who}

Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all
copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE
SOFTWARE."""
if missing:
    L.append("## Crates whose package has no licence file\n")
    L.append("These crates declare their licence in their metadata but their published package holds no licence file. The SPDX expression applies. Where it offers MIT, the standard MIT text is given with the authors named in the crate's metadata; for any other licence the standard text is at https://spdx.org/licenses/ (the Apache-2.0 text appears above in this file).\n")
    for p in pkgs:
        if "%s %s" % (p["name"], p["version"]) not in missing:
            continue
        lic = p.get("license") or "UNKNOWN"
        who = ", ".join(a.split("<")[0].strip() for a in p.get("authors") or []) or "the authors of %s" % p["name"]
        L.append("### %s %s (%s)\n" % (p["name"], p["version"], lic))
        if p.get("repository"):
            L.append("Source: %s\n" % p["repository"])
        if "MIT" in lic:
            L.append("```text\n%s\n```\n" % MIT.format(who=who))
    L.append("")

data = "\n".join(L)
if check:
    cur = open(out, encoding="utf-8").read() if os.path.exists(out) else ""
    sys.exit(0 if cur == data else 1)
open(out, "w", encoding="utf-8").write(data)
print("wrote %s: %d crates, %d licence groups, %d without a licence file" % (out, len(pkgs), len(groups), len(missing)))
